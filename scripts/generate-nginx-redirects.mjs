import { existsSync, statSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { registerHooks } from 'node:module'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const projectRoot = process.cwd()
const outputPath = path.join(projectRoot, 'ops', 'nginx', 'snippets', 'redirects.conf')

function findProjectModule(basePath) {
  const candidates = [
    basePath,
    `${basePath}.ts`,
    `${basePath}.tsx`,
    `${basePath}.js`,
    path.join(basePath, 'index.ts'),
    path.join(basePath, 'index.tsx'),
    path.join(basePath, 'index.js'),
  ]

  return candidates.find((candidate) => {
    try {
      return statSync(candidate).isFile()
    } catch {
      return false
    }
  })
}

registerHooks({
  resolve(specifier, context, nextResolve) {
    let basePath

    if (specifier.startsWith('@/')) {
      basePath = path.join(projectRoot, 'src', specifier.slice(2))
    } else if (
      (specifier.startsWith('./') || specifier.startsWith('../')) &&
      context.parentURL?.startsWith('file:')
    ) {
      basePath = path.resolve(path.dirname(fileURLToPath(context.parentURL)), specifier)
    }

    if (basePath) {
      const resolved = findProjectModule(basePath)
      if (resolved) return { url: pathToFileURL(resolved).href, shortCircuit: true }
    }

    return nextResolve(specifier, context)
  },
})

function normalizeRedirectPath(value, label) {
  if (typeof value !== 'string' || !value.startsWith('/') || !value.endsWith('/')) {
    throw new Error(`${label} must be an absolute trailing-slash path: ${String(value)}`)
  }
  if (value !== new URL(value, 'https://redirect.invalid').pathname || /[\r\n;{}$]/.test(value)) {
    throw new Error(`${label} contains unsafe or non-path characters: ${value}`)
  }
  return value.replace(/\/{2,}/g, '/')
}

export function renderNginxRedirects(rules, manifest) {
  if (manifest?.schema !== 'ams-route-artifact-v1' || !Array.isArray(manifest.routes)) {
    throw new Error('Repository route manifest has an unsupported shape')
  }

  const routePaths = new Set(
    manifest.routes.map((route) => normalizeRedirectPath(route.path, 'Manifest route')),
  )
  const normalized = rules.map((rule) => ({
    source: normalizeRedirectPath(rule.source, 'Redirect source'),
    destination: normalizeRedirectPath(rule.destination, 'Redirect destination'),
    permanent: rule.permanent,
  }))
  const destinations = new Map()

  for (const rule of normalized) {
    if (rule.permanent !== true) throw new Error(`Redirect must be permanent: ${rule.source}`)
    if (rule.source === rule.destination) throw new Error(`Redirect points to itself: ${rule.source}`)
    if (destinations.has(rule.source)) throw new Error(`Duplicate redirect source: ${rule.source}`)
    destinations.set(rule.source, rule.destination)
  }

  for (const rule of normalized) {
    if (!routePaths.has(rule.destination)) {
      throw new Error(`Redirect target is absent from repository route manifest: ${rule.destination}`)
    }
    if (destinations.has(rule.destination)) {
      throw new Error(`Redirect chain or loop is not allowed: ${rule.source} -> ${rule.destination}`)
    }
  }

  const blocks = normalized
    .sort((left, right) => left.source.localeCompare(right.source))
    .map(
      ({ source, destination }) =>
        `location = ${source} {\n  return 301 ${destination};\n}`,
    )

  return [
    '# Generated by scripts/generate-nginx-redirects.mjs. Do not edit.',
    '# Source: src/project/redirects.ts; targets: repository route artifact manifest.',
    '',
    ...blocks.flatMap((block, index) => (index === blocks.length - 1 ? [block] : [block, ''])),
    '',
  ].join('\n')
}

export function assertGeneratedFile(expected, actual) {
  if (actual !== expected) {
    throw new Error('Generated Nginx redirects are stale; run pnpm generate:nginx-redirects')
  }
}

async function loadCanonicalInputs() {
  const [{ redirects }, { buildRouteArtifactManifest }] = await Promise.all([
    import('../src/project/redirects.ts'),
    import('../src/core/seo/route-artifact-manifest.ts'),
  ])

  return { redirects, manifest: await buildRouteArtifactManifest() }
}

async function runSelfTest() {
  const manifest = {
    schema: 'ams-route-artifact-v1',
    routes: [{ path: '/a/' }, { path: '/b/' }, { path: '/target/' }],
  }
  const expected = [
    '# Generated by scripts/generate-nginx-redirects.mjs. Do not edit.',
    '# Source: src/project/redirects.ts; targets: repository route artifact manifest.',
    '',
    'location = /a/ {',
    '  return 301 /target/;',
    '}',
    '',
    'location = /b/ {',
    '  return 301 /target/;',
    '}',
    '',
  ].join('\n')
  const rendered = renderNginxRedirects(
    [
      { source: '/b/', destination: '/target/', permanent: true },
      { source: '/a/', destination: '/target/', permanent: true },
    ],
    manifest,
  )
  if (rendered !== expected) throw new Error('Generator output is not deterministic')
  assertGeneratedFile(expected, rendered)

  const rejected = [
    {
      name: 'missing target',
      rules: [{ source: '/a/', destination: '/missing/', permanent: true }],
      pattern: /absent from repository route manifest/,
    },
    {
      name: 'loop',
      rules: [
        { source: '/a/', destination: '/b/', permanent: true },
        { source: '/b/', destination: '/a/', permanent: true },
      ],
      pattern: /chain or loop/,
    },
    {
      name: 'non-permanent redirect',
      rules: [{ source: '/a/', destination: '/target/', permanent: false }],
      pattern: /must be permanent/,
    },
  ]

  for (const fixture of rejected) {
    try {
      renderNginxRedirects(fixture.rules, manifest)
      throw new Error(`Self-test fixture did not fail: ${fixture.name}`)
    } catch (error) {
      if (!fixture.pattern.test(String(error))) throw error
    }
  }

  try {
    assertGeneratedFile(expected, `${expected}# drift\n`)
    throw new Error('Drift fixture did not fail')
  } catch (error) {
    if (!/stale/.test(String(error))) throw error
  }

  console.log('Nginx redirect generator self-test: PASS')
}

async function main() {
  if (process.argv.includes('--self-test')) {
    await runSelfTest()
    return
  }

  const { redirects, manifest } = await loadCanonicalInputs()
  const rendered = renderNginxRedirects(redirects, manifest)

  if (process.argv.includes('--check')) {
    const current = existsSync(outputPath) ? await readFile(outputPath, 'utf8') : ''
    assertGeneratedFile(rendered, current)
    console.log(`Generated Nginx redirects: PASS (${redirects.length} rules)`)
    return
  }

  await mkdir(path.dirname(outputPath), { recursive: true })
  await writeFile(outputPath, rendered, 'utf8')
  console.log(`Generated Nginx redirects: wrote ${redirects.length} rules`)
}

await main()
